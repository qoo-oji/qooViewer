import Foundation

/// 「この本を、どこに開くか」の指定。
///
/// ■ なぜ`asTab: Bool`ではなく列挙なのか
/// これまで「新しいウインドウ/タブで開く」の経路はどれも`asTab: Bool`1つで表されており、
/// シークレットかどうかは常に**派生元のウインドウから引き継ぐ**もの(BookWindowGroup参照)
/// だった。サイドパネル等の右クリックメニューに「新規ノーマルウインドウで開く」
/// 「新規シークレットウインドウで開く」を足したことで、**ユーザーがその場でどちらかを
/// 明示的に選ぶ**という選択肢が増え、Bool 1つでは表せなくなった。
///
/// どの選択肢が実際にどのWindowGroupになるかは`BookWindowGroup.id(for:inheritingFrom:)`が
/// 1箇所で持つ(判断を散らさないため。そちらのコメント参照)。実際に開く手順は
/// `BookWindowOpener.open(_:to:from:...)`が1箇所で持つ。
enum BookOpenDestination: Hashable, Sendable, CaseIterable {
    /// 新しいウインドウ。シークレットかどうかは派生元のウインドウから引き継ぐ。
    /// 従来からある「新しいウインドウで開く…」(ファイルメニュー・お気に入り一覧・
    /// 環境設定「Finderから」「お気に入りを開くとき」)がこれ。
    case newWindow

    /// 新しいウインドウ。派生元が何であれ**必ず記録の残る通常のウインドウ**。
    case newNormalWindow

    /// 新しいウインドウ。派生元が何であれ**必ずシークレットウインドウ**。
    case newPrivateWindow

    /// 新しいタブ。シークレットかどうかは派生元のウインドウから引き継ぐ。
    ///
    /// **タブには「ノーマル/シークレットを選ぶ」版を用意しない。** macOSのタブは1枚の
    /// ウインドウを共有するため、記録の残るタブと残らないタブが同じタブバーに並ぶことに
    /// なり、今どちらを見ているのかタイトルバーからは分からなくなる(タイトルの
    /// 「(シークレット)」表示は最前面のタブのぶんしか出ない)。シークレットウインドウの
    /// 意味そのものが壊れるので、タブは派生元を引き継ぐこの1つだけにしてある。
    case newTab

    /// タブとして開く指定かどうか(既存の`asTab: Bool`との橋渡し)。
    var isTab: Bool { self == .newTab }
}
