import SwiftUI

/// 環境設定ウインドウのポップアップ(Picker)で選ばせる列挙型の共通インターフェース。
///
/// これまで各enumは `titleKey` 1本だけを持っていたが、それがそのまま
/// 「ポップアップを閉じた状態に出る文字列」でもあったため、意味を正確に伝えようとするほど
/// 文字列が長くなり、閉じた状態では省略され(「前回表示したページから…」)、
/// 逆に何が選ばれているのか分からなくなる、という板挟みになっていた。
///
/// そこで環境設定のポップアップ専用に、**短い名前**(`shortTitleKey`)を別に持たせる。
/// 名詞句で、閉じた状態でも省略されない長さにすること。
///
/// ■ 説明文(`detailKey`)は廃止した
/// 以前はこれと対で、選択肢ごとに1文の説明 `detailKey` を持たせ、選ばれている項目のぶんを
/// コントロールの下に出していた。しかし環境設定全体で説明文が増えすぎて認知コストが高くなり、
/// 整理の過程で「このアプリを使う人には選択肢名だけで十分。説明が要るなら、それは
/// 選択肢名のほうが悪い」という判断に至って削除した(ユーザーの指示)。
///
/// したがって `shortTitleKey` は、**それ単体で意味が通る**必要がある。
/// 説明を足したくなったら、まず名前のほうを見直すこと。
protocol SettingsOption: CaseIterable, Identifiable, Hashable {
    /// ポップアップの行および閉じた状態に表示する短い名前。
    var shortTitleKey: LocalizedStringKey { get }
}
