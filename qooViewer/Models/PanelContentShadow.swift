import SwiftUI

/// すりガラスの面に載る文字・アイコンの背後へ敷く影の強さ。0(なし)〜5の6段階。
///
/// ■ 何のためにあるのか
/// ユーザー報告: すりガラスの重ね色を黒・濃さ100%にすると、ライト外観で文字とボタンが
/// 見えなくなる。ライト外観の文字色は黒のままなので、黒く塗り潰した面の上では黒地に黒になる
/// (ダーク外観で白100%にすると同じことが裏返しで起きる)。
///
/// これを「面の明るさから文字色を自動的に反転させる」形で直すことも検討したが、**採らなかった**。
/// 面の下にあるのはページ画像で、その色は知りようが無い ―― すりガラスも重ね色も薄いときは
/// どう推定しても外すケースが残り、しかも推定が外れると**従来は読めていた場所まで壊す**
/// (実測で確認済み)。判断はユーザーに委ねることにした。
///
/// 影は文字色の反対色で敷くため、**下地が何色であっても輪郭が残る**。黒地に黒い文字でも、
/// 白い画像の上に白い文字でも、輪郭さえ出れば読める ―― 推定を一切必要としない解決になっている。
///
/// ■ ぼかさない
/// 最初はガウスぼかしの影(`.shadow(radius:)`)で作ったが、**採らなかった**。黒く塗り潰した面の
/// 上の黒い文字は文字自体が見えないため、ぼかした影だけが残って「白くにじんだ幽霊」のように
/// 見えてしまう(実測で確認)。ユーザーの求めているものは「本来のボタンや文字はにじませず、
/// 背景だけに付ける」ものだった。
///
/// そこで、**文字・アイコンの形そのままの輪郭**を、反対色で少しだけ太らせて後ろへ敷く。
/// グリフ自体は一切ぼけず、黒地に黒い文字でも「白い縁取りの中の黒い文字」として くっきり読める。実装は半径0の影を上下左右へずらして重ねるだけで、SwiftUIだけで完結する。
///
/// 段階は輪郭の太さ(pt)。細い線画のアイコンでも潰れない太さから、はっきり縁取る太さまで。
///
/// 既定は0(なし)。設定を触っていない人の画面は1ピクセルも変わらない。
enum PanelContentShadow {
    /// スライダーが取りうる段階。0がなし。
    static let range: ClosedRange<Int> = 0...5

    /// 範囲外の値(UserDefaultsを直接書き換えられていた場合)を丸める。
    static func clampedLevel(_ level: Int) -> Int {
        min(range.upperBound, max(range.lowerBound, level))
    }

    /// 段階に対応する輪郭の太さ(pt)。0なら輪郭なし。**0.25pt刻みの5段階**(ユーザーの指定)。
    ///
    /// 最小の0.25ptはRetinaで**半ピクセル**にあたり、アンチエイリアスでグリフのふちに
    /// うっすら沿うだけの細さになる。1物理ピクセル(0.5pt)から始めた版は「2以上は色がかぶって、
    /// 特にボタンの図形が灰色に見える」と指摘を受けて刻み直した。
    ///
    /// なぜ太らせると灰色に見えるのかも実測で分かっている ―― **ツールバーのアイコンはそもそも
    /// 黒ではなく中間グレー(輝度120前後)で描かれている**(`.buttonStyle(.borderless)`の既定色。
    /// PanelIconButtonLabelが無効時の淡色表示を殺さないため前景色を指定していないので、この色は
    /// アプリ側では決めていない)。輪郭を太らせるほど白い面積が増え、その上に灰色のグリフが乗る
    /// 形になるため、図形全体が灰色っぽく見える。細いほどこの印象は弱まる。
    ///
    /// そのため下の段階ほど細い線画(SF Symbolsの`chevron`など)向き、上の段階ほど本文向き。
    static func outlineWidth(forLevel level: Int) -> CGFloat {
        // 0.25pt刻み。段階を増やすときもこの刻みを保つこと。
        CGFloat(clampedLevel(level)) * 0.25
    }

    /// 輪郭を作るためにグリフをずらす方向(単位ベクトル)。**上下左右の4方向だけ**。
    ///
    /// `.shadow`は連鎖させると、前段の影まで含めた形をさらにずらして重ねる。そのため方向を
    /// 増やすほど太りが累積し、**指定した太さの2〜3倍**になってしまう(斜めを含む8方向で
    /// 実装したところ、最小段階でも太すぎるとユーザーから指摘を受けた)。
    ///
    /// 4方向だけなら、累積するのは「+xと+y」のような直交する組み合わせだけで、各軸方向の
    /// 張り出しは`width`ちょうどに収まる(角が45度方向へわずかに出るが、この太さでは見えない)。
    /// **方向を足すときはこの性質が崩れることに注意。**
    static let outlineDirections: [(x: CGFloat, y: CGFloat)] = [
        (1, 0), (-1, 0), (0, 1), (0, -1),
    ]

    /// スライダーの現在値として表示する文字列。0だけ「なし」と言葉で示す
    /// (「0」だと、影の強さが0なのか段階の名前なのかが紛らわしいため)。
    static func displayText(forLevel level: Int, locale: Locale) -> String {
        let level = clampedLevel(level)
        guard level > 0 else { return String(localized: "None", locale: locale) }
        return "\(level)"
    }
}
